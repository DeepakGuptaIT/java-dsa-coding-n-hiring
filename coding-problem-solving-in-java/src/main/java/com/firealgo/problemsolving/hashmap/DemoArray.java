package com.firealgo.problemsolving.hashmap;

import java.util.Arrays;

public class DemoArray {


    public static void main(String[] args) {
        int[] nums = new int[3];
        for (int i = 0; i < nums.length; i++) {
            nums[i]++;
        }
        System.out.println(Arrays.toString(nums));
    }
}
